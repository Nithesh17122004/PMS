ACCENT = colors.HexColor("#1d4ed8")
TEAL = colors.HexColor("#0f9d8f")
DARK = colors.HexColor("#0f172a")
MUTED = colors.HexColor("#64748b")
LIGHT = colors.HexColor("#f1f5f9")
BORDER = colors.HexColor("#e2e8f0")


def _safe(text) -> str:
    return str(text or "").encode("latin-1", "replace").decode("latin-1")


def _styles():
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(name="ClinicName", fontName="Helvetica-Bold", fontSize=16, leading=19, textColor=DARK))
    styles.add(ParagraphStyle(name="ClinicMeta", fontName="Helvetica", fontSize=8.5, leading=11, textColor=MUTED))
    styles.add(ParagraphStyle(name="DocTitle", fontName="Helvetica-Bold", fontSize=13, leading=16, textColor=ACCENT, alignment=TA_RIGHT))
    styles.add(ParagraphStyle(name="Section", fontName="Helvetica-Bold", fontSize=9.5, leading=12, textColor=DARK, spaceBefore=8, spaceAfter=4))
    styles.add(ParagraphStyle(name="SmallMuted", fontName="Helvetica", fontSize=8, leading=10, textColor=MUTED))
    styles.add(ParagraphStyle(name="TokenNumber", fontName="Helvetica-Bold", fontSize=64, leading=70, textColor=ACCENT, alignment=TA_CENTER))
    styles.add(ParagraphStyle(name="Center", fontName="Helvetica", fontSize=9, leading=12, alignment=TA_CENTER))
    styles.add(ParagraphStyle(name="Right", fontName="Helvetica", fontSize=9, leading=12, alignment=TA_RIGHT))
    styles.add(ParagraphStyle(name="BodySmall", fontName="Helvetica", fontSize=9, leading=12, textColor=DARK))
    return styles


def _header_footer(canvas, doc, clinic, title: str, subtitle: str = ""):
    canvas.saveState()
    width, height = A4
    canvas.setFillColor(DARK)
    canvas.rect(0, height - 32 * mm, width, 32 * mm, fill=1, stroke=0)
    canvas.setFillColor(colors.white)
    canvas.setFont("Helvetica-Bold", 17)
    canvas.drawString(18 * mm, height - 15 * mm, _safe(clinic.name))
    canvas.setFont("Helvetica", 8)
    address = ", ".join(
        [part for part in [clinic.address_line1, clinic.city, clinic.state, clinic.postal_code] if part]
    )
    canvas.drawString(18 * mm, height - 20 * mm, _safe(address))
    contact = " · ".join([part for part in [clinic.phone, clinic.email] if part])
    canvas.drawString(18 * mm, height - 24.5 * mm, _safe(contact))
    canvas.setFont("Helvetica-Bold", 13)
    canvas.drawRightString(width - 18 * mm, height - 15 * mm, _safe(title))
    canvas.setFont("Helvetica", 8)
    if subtitle:
        canvas.drawRightString(width - 18 * mm, height - 20 * mm, _safe(subtitle))
    canvas.setStrokeColor(TEAL)
    canvas.setLineWidth(1.5)
    canvas.line(18 * mm, height - 32 * mm, width - 18 * mm, height - 32 * mm)
    canvas.setFillColor(MUTED)
    canvas.setFont("Helvetica", 7.5)
    footer = "Generated by ClinicFlow"
    if clinic.is_demo:
        footer += " · DEMONSTRATION DATA — NOT A REAL MEDICAL RECORD"
    canvas.drawString(18 * mm, 10 * mm, footer)
    canvas.drawRightString(width - 18 * mm, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


def _document(title, clinic, subtitle=""):
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=40 * mm,
        bottomMargin=18 * mm,
        title=title,
        author=clinic.name,
    )
    doc._clinicflow_header = lambda canvas, doc_: _header_footer(canvas, doc_, clinic, title, subtitle)
    return buffer, doc


def _build(doc, buffer, story):
    doc.build(story, onFirstPage=doc._clinicflow_header, onLaterPages=doc._clinicflow_header)
    buffer.seek(0)
    return buffer


def _info_table(rows, styles, widths=None):
    table = Table(rows, colWidths=widths)
    table.setStyle(
        TableStyle(
            [
                ("FONTNAME", (0, 0), (-1, -1), "Helvetica"),
                ("FONTSIZE", (0, 0), (-1, -1), 8.8),
                ("TEXTCOLOR", (0, 0), (-1, -1), DARK),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("LINEBELOW", (0, 0), (-1, -2), 0.4, BORDER),
            ]
        )
    )
    return table


def token_receipt_pdf(token) -> io.BytesIO:
    clinic = token.doctor.clinic
    styles = _styles()
    subtitle = f"{token.token_date.strftime('%d %b %Y')} · Token"
    buffer, doc = _document("Token Receipt", clinic, subtitle)
    story = [
        Spacer(1, 2 * mm),
        Paragraph(_safe(token.display_number), styles["TokenNumber"]),
        Paragraph(_safe(f"Queue for {token.doctor.full_name}"), styles["Center"]),
        Spacer(1, 6 * mm),
    ]
    rows = [
        ["Patient", _safe(token.patient.full_name), "Patient ID", _safe(token.patient.patient_code)],
        ["Doctor", _safe(token.doctor.full_name), "Specialty", _safe(token.doctor.specialization)],
        ["Visit type", _safe(token.visit_type.replace("_", " ").title()), "Date", token.token_date.strftime("%d %b %Y")],
        ["Issued at", token.created_at.astimezone().strftime("%I:%M %p"), "Status", token.status.replace("_", " ").title()],
    ]
    story.append(_info_table(rows, styles, widths=[28 * mm, 60 * mm, 24 * mm, 56 * mm]))
    story.append(Spacer(1, 8 * mm))
    story.append(
        Paragraph(
            _safe(
                (clinic.settings.display_message if clinic.settings else "")
                or "Please wait in the waiting area. Keep this receipt with you."
            ),
            styles["Center"],
        )
    )
    story.append(Spacer(1, 4 * mm))
    story.append(Paragraph(_safe((clinic.settings.receipt_footer if clinic.settings else "") or ""), styles["SmallMuted"]))
    return _build(doc, buffer, story)


def prescription_pdf(prescription) -> io.BytesIO:
    clinic = prescription.doctor.clinic
    styles = _styles()
    subtitle = f"{prescription.prescription_code} · {prescription.issued_at.strftime('%d %b %Y')}"
    buffer, doc = _document("Prescription", clinic, subtitle)
    story = []
    patient = prescription.patient
    doctor = prescription.doctor
    rows = [
        ["Patient", _safe(patient.full_name), "Patient ID", _safe(patient.patient_code)],
        ["Age / Gender", f"{patient.age or '—'} / {_safe(patient.gender.title())}", "Date", prescription.issued_at.strftime("%d %b %Y")],
        ["Doctor", _safe(doctor.full_name), "Registration", _safe(doctor.registration_number or "—")],
        ["Specialty", _safe(doctor.specialization), "Qualifications", _safe(doctor.qualifications or "—")],
    ]
    story.append(_info_table(rows, styles, widths=[28 * mm, 60 * mm, 24 * mm, 56 * mm]))
    story.append(Spacer(1, 5 * mm))
    if patient.allergies:
        allergy = Table(
            [[Paragraph(f"<b>Allergies:</b> {_safe(patient.allergies)}", styles["BodySmall"])]],
            colWidths=[168 * mm],
        )
        allergy.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#fff7ed")), ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#fdba74")), ("LEFTPADDING", (0, 0), (-1, -1), 6), ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5)]))
        story.append(allergy)
        story.append(Spacer(1, 4 * mm))
    story.append(Paragraph("Medicines", styles["Section"]))
    data = [["#", "Medicine", "Dosage", "Frequency", "Duration", "Qty", "Instructions"]]
    for index, item in enumerate(prescription.items, start=1):
        name = item.medicine_name + (f" {item.strength}" if item.strength else "")
        data.append(
            [
                str(index),
                Paragraph(_safe(name), styles["BodySmall"]),
                _safe(item.dosage),
                _safe(item.frequency),
                f"{item.duration_days or '—'} days" if item.duration_days else "—",
                _safe(item.quantity or "—"),
                Paragraph(_safe(item.instructions or ""), styles["SmallMuted"]),
            ]
        )
    table = Table(data, colWidths=[7 * mm, 47 * mm, 24 * mm, 26 * mm, 20 * mm, 12 * mm, 32 * mm], repeatRows=1)
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), LIGHT),
                ("TEXTCOLOR", (0, 0), (-1, 0), DARK),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, 0), 8),
                ("FONTSIZE", (0, 1), (-1, -1), 8),
                ("FONTNAME", (0, 1), (-1, -1), "Helvetica"),
                ("GRID", (0, 0), (-1, -1), 0.35, BORDER),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#fbfdff")]),
            ]
        )
    )
    story.append(table)
    if prescription.notes:
        story.append(Spacer(1, 4 * mm))
        story.append(Paragraph("Notes", styles["Section"]))
        story.append(Paragraph(_safe(prescription.notes), styles["BodySmall"]))
    story.append(Spacer(1, 14 * mm))
    signature = Table(
        [[Paragraph(_safe(doctor.full_name), styles["BodySmall"]), Paragraph("Doctor's signature", styles["Right"])]],
        colWidths=[84 * mm, 84 * mm],
    )
    signature.setStyle(TableStyle([("LINEABOVE", (0, 0), (0, 0), 0.5, BORDER), ("LINEABOVE", (1, 0), (1, 0), 0.5, BORDER), ("TOPPADDING", (0, 0), (-1, -1), 6)]))
    story.append(signature)
    story.append(Spacer(1, 4 * mm))
    story.append(Paragraph("This prescription is valid only when issued by a registered medical practitioner. Digitally generated by ClinicFlow.", styles["SmallMuted"]))
    return _build(doc, buffer, story)


def invoice_pdf(invoice) -> io.BytesIO:
    clinic = invoice.patient.clinic if hasattr(invoice.patient, "clinic") else None
    # Clinic relationship is not on patient; resolve via invoice clinic id.
    from ..models import Clinic

    clinic = Clinic.query.get(invoice.clinic_id)
    styles = _styles()
    subtitle = f"{invoice.invoice_number} · {invoice.issued_at.strftime('%d %b %Y') if invoice.issued_at else ''}"
    buffer, doc = _document("Invoice", clinic, subtitle)
    story = []
    rows = [
        ["Patient", _safe(invoice.patient.full_name), "Patient ID", _safe(invoice.patient.patient_code)],
        ["Phone", _safe(invoice.patient.phone or "—"), "Status", invoice.status.replace("_", " ").title()],
        ["Issued", invoice.issued_at.strftime("%d %b %Y") if invoice.issued_at else "—", "Due", invoice.due_date.strftime("%d %b %Y") if invoice.due_date else "—"],
    ]
    story.append(_info_table(rows, styles, widths=[28 * mm, 60 * mm, 24 * mm, 56 * mm]))
    story.append(Spacer(1, 5 * mm))
    data = [["Description", "Qty", "Unit price", "Amount"]]
    for item in invoice.items:
        data.append([_safe(item.description), str(item.quantity), f"Rs. {item.unit_price:,.2f}", f"Rs. {item.amount:,.2f}"])
    table = Table(data, colWidths=[96 * mm, 18 * mm, 28 * mm, 26 * mm])
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), LIGHT),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTNAME", (0, 1), (-1, -1), "Helvetica"),
                ("FONTSIZE", (0, 0), (-1, -1), 8.5),
                ("GRID", (0, 0), (-1, -1), 0.35, BORDER),
                ("ALIGN", (1, 0), (-1, -1), "RIGHT"),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ]
        )
    )
    story.append(table)
    story.append(Spacer(1, 4 * mm))
    totals = [
        ["Subtotal", f"Rs. {invoice.subtotal:,.2f}"],
        ["Discount", f"- Rs. {invoice.discount_amount:,.2f}"],
        [f"Tax ({invoice.tax_rate}%)", f"Rs. {invoice.tax_amount:,.2f}"],
        ["Total", f"Rs. {invoice.total:,.2f}"],
        ["Paid", f"Rs. {invoice.amount_paid:,.2f}"],
        ["Balance due", f"Rs. {invoice.balance:,.2f}"],
    ]
    totals_table = Table(totals, colWidths=[40 * mm, 32 * mm], hAlign="RIGHT")
    totals_table.setStyle(
        TableStyle(
            [
                ("FONTSIZE", (0, 0), (-1, -1), 8.5),
                ("ALIGN", (1, 0), (1, -1), "RIGHT"),
                ("FONTNAME", (0, 3), (-1, -1), "Helvetica-Bold"),
                ("LINEABOVE", (0, 3), (-1, 3), 0.6, BORDER),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ]
        )
    )
    story.append(totals_table)
    if invoice.payments:
        story.append(Paragraph("Payments", styles["Section"]))
        payment_data = [["Receipt", "Method", "Date", "Amount"]]
        for payment in invoice.payments:
            payment_data.append([payment.payment_code, payment.method.replace("_", " ").title(), payment.paid_at.strftime("%d %b %Y"), f"Rs. {payment.amount:,.2f}"])
        pt = Table(payment_data, colWidths=[36 * mm, 30 * mm, 30 * mm, 28 * mm])
        pt.setStyle(TableStyle([("FONTSIZE", (0, 0), (-1, -1), 8), ("BACKGROUND", (0, 0), (-1, 0), LIGHT), ("GRID", (0, 0), (-1, -1), 0.35, BORDER), ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4)]))
        story.append(pt)
    if invoice.notes:
        story.append(Spacer(1, 4 * mm))
        story.append(Paragraph("Notes", styles["Section"]))
        story.append(Paragraph(_safe(invoice.notes), styles["BodySmall"]))
    return _build(doc, buffer, story)


def lab_report_pdf(order) -> io.BytesIO:
    clinic = order.patient.clinic if hasattr(order.patient, "clinic") else None
    from ..models import Clinic

    clinic = Clinic.query.get(order.clinic_id)
    styles = _styles()
    subtitle = f"{order.order_number} · {order.ordered_at.strftime('%d %b %Y')}"
    buffer, doc = _document("Laboratory Report", clinic, subtitle)
    story = []
    rows = [
        ["Patient", _safe(order.patient.full_name), "Patient ID", _safe(order.patient.patient_code)],
        ["Age / Gender", f"{order.patient.age or '—'} / {_safe(order.patient.gender.title())}", "Ordered", order.ordered_at.strftime("%d %b %Y")],
        ["Doctor", _safe(order.doctor.full_name if order.doctor else "—"), "Status", order.status.replace("_", " ").title()],
    ]
    story.append(_info_table(rows, styles, widths=[28 * mm, 60 * mm, 24 * mm, 56 * mm]))
    story.append(Spacer(1, 5 * mm))
    data = [["Test", "Result", "Unit", "Reference", "Interpretation"]]
    for item in order.items:
        result = item.result
        data.append(
            [
                Paragraph(_safe(item.test.name), styles["BodySmall"]),
                _safe(result.result_value if result else "Pending"),
                _safe(result.unit if result else ""),
                _safe(result.reference_range if result else item.test.reference_range or ""),
                _safe(result.interpretation.title() if result else "—"),
            ]
        )
    table = Table(data, colWidths=[58 * mm, 32 * mm, 18 * mm, 38 * mm, 22 * mm])
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), LIGHT),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 8.5),
                ("GRID", (0, 0), (-1, -1), 0.35, BORDER),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ]
        )
    )
    story.append(table)
    story.append(Spacer(1, 8 * mm))
    verified = [item.result.verified_by for item in order.items if item.result and item.result.verified_at]
    story.append(Paragraph("Results are for clinical correlation. Please consult the ordering doctor.", styles["SmallMuted"]))
    if verified:
        story.append(Paragraph("Verified by laboratory staff.", styles["SmallMuted"]))
    return _build(doc, buffer, story)


def report_pdf(title: str, clinic, columns, rows, summary=None, date_label="") -> io.BytesIO:
    styles = _styles()
    buffer, doc = _document(title, clinic, date_label)
    story = [Spacer(1, 2 * mm)]
    if summary:
        summary_rows = [[str(k), str(v)] for k, v in summary.items()]
        summary_table = Table(summary_rows, colWidths=[70 * mm, 40 * mm], hAlign="LEFT")
        summary_table.setStyle(TableStyle([("FONTSIZE", (0, 0), (-1, -1), 8.5), ("BOTTOMPADDING", (0, 0), (-1, -1), 2), ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold")]))
        story.append(summary_table)
        story.append(Spacer(1, 4 * mm))
    data = [columns] + rows
    width = 168 * mm / max(1, len(columns))
    table = Table(data, colWidths=[width] * len(columns), repeatRows=1)
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), LIGHT),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 7.5),
                ("GRID", (0, 0), (-1, -1), 0.3, BORDER),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ]
        )
    )
    story.append(table)
    if not rows:
        story.append(Spacer(1, 6 * mm))
        story.append(Paragraph("No records matched the selected filters.", styles["SmallMuted"]))
    return _build(doc, buffer, story)
